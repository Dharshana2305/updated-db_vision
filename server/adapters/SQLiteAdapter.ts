import initSqlJs, { Database, SqlJsStatic } from 'sql.js';
import fs from 'fs';
import { DatabaseAdapter, AdapterCapabilities, ConnectionTestResult } from './DatabaseAdapter.js';
import { DatabaseSchema, TableSchema, ColumnSchema, ForeignKeySchema, IndexSchema, QueryResult } from '../../src/types.js';

let SQLModule: SqlJsStatic | null = null;

export class SQLiteAdapter implements DatabaseAdapter {
  readonly type = 'sqlite' as const;
  private db: Database | null = null;
  private dbBuffer: Buffer | null = null;
  private filePath?: string;
  private rawSqlInit?: string;
  private databaseName = 'main';

  constructor(options?: { filePath?: string; fileBuffer?: Buffer; rawSql?: string; databaseName?: string }) {
    if (options?.filePath) this.filePath = options.filePath;
    if (options?.fileBuffer) this.dbBuffer = options.fileBuffer;
    if (options?.rawSql) this.rawSqlInit = options.rawSql;
    if (options?.databaseName) this.databaseName = options.databaseName;
  }

  getCapabilities(): AdapterCapabilities {
    return {
      supportsSQL: true,
      supportsNoSQL: false,
      supportsForeignKeys: true,
      supportsIndexes: true,
      supportsExplainPlan: true,
      supportsSafeModifications: true,
      supportsTransactions: true,
      supportsBenchmark: true,
      supportsDataProfiling: true,
      supportsDirectRollback: true,
      supportedConnectionTypes: ['fileUpload', 'sampleDatabase', 'connectionString']
    };
  }

  private async getSqlModule(): Promise<SqlJsStatic> {
    if (!SQLModule) {
      SQLModule = await initSqlJs();
    }
    return SQLModule;
  }

  async connect(): Promise<boolean> {
    try {
      const SQL = await this.getSqlModule();

      if (this.dbBuffer) {
        this.db = new SQL.Database(new Uint8Array(this.dbBuffer));
      } else if (this.filePath && fs.existsSync(this.filePath)) {
        if (this.filePath.toLowerCase().endsWith('.sql')) {
          this.db = new SQL.Database();
          const sqlText = fs.readFileSync(this.filePath, 'utf-8');
          this.db.exec(sqlText);
        } else {
          const fileData = fs.readFileSync(this.filePath);
          this.db = new SQL.Database(new Uint8Array(fileData));
        }
      } else {
        this.db = new SQL.Database();
      }

      if (this.rawSqlInit) {
        this.db.exec(this.rawSqlInit);
      }

      // Performance pragma settings for fast memory operations on large files (up to 150MB)
      try {
        this.db.exec('PRAGMA synchronous = OFF; PRAGMA journal_mode = MEMORY; PRAGMA cache_size = -64000;');
      } catch {}

      // Enable foreign key support in SQLite
      this.db.exec('PRAGMA foreign_keys = ON;');
      return true;
    } catch (err) {
      console.error('Failed to initialize SQLite connection:', err);
      return false;
    }
  }

  async disconnect(): Promise<void> {
    if (this.db) {
      this.db.close();
      this.db = null;
    }
  }

  /**
   * Exports the live, updated SQLite database as a binary buffer
   */
  exportBinaryDatabase(): Buffer {
    if (!this.db) throw new Error('Database not connected');
    const u8 = this.db.export();
    return Buffer.from(u8);
  }

  /**
   * Exports the live, updated SQLite database as a complete SQL script (.sql)
   */
  exportSqlDump(): string {
    if (!this.db) throw new Error('Database not connected');
    const tablesRes = this.db.exec("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name ASC;");
    const indicesRes = this.db.exec("SELECT name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%';");

    let dump = `-- ========================================================\n`;
    dump += `-- Hardened & Remediated Database Schema Export\n`;
    dump += `-- Database Name: ${this.databaseName}\n`;
    dump += `-- Exported At: ${new Date().toISOString()}\n`;
    dump += `-- Generated by AI-Powered Database Reviewer\n`;
    dump += `-- ========================================================\n\n`;
    dump += `PRAGMA foreign_keys = ON;\n`;
    dump += `BEGIN TRANSACTION;\n\n`;

    const tables = tablesRes[0]?.values || [];
    for (const [name, sql] of tables) {
      if (!name || !sql) continue;
      dump += `-- --------------------------------------------------------\n`;
      dump += `-- Table structure for "${name}"\n`;
      dump += `-- --------------------------------------------------------\n`;
      dump += `${sql};\n\n`;

      // Export row data for this table
      try {
        const rowsRes = this.db.exec(`SELECT * FROM "${name}";`);
        if (rowsRes.length > 0 && rowsRes[0].values.length > 0) {
          const cols = rowsRes[0].columns.map(c => `"${c}"`).join(', ');
          dump += `-- Data for table "${name}" (${rowsRes[0].values.length} records)\n`;
          for (const row of rowsRes[0].values) {
            const vals = row.map(v => {
              if (v === null || v === undefined) return 'NULL';
              if (typeof v === 'number') return v;
              return `'${String(v).replace(/'/g, "''")}'`;
            }).join(', ');
            dump += `INSERT INTO "${name}" (${cols}) VALUES (${vals});\n`;
          }
          dump += '\n';
        }
      } catch (err) {
        console.warn(`Export data rows failed for table ${name}:`, err);
      }
    }

    const indices = indicesRes[0]?.values || [];
    if (indices.length > 0) {
      dump += `-- --------------------------------------------------------\n`;
      dump += `-- Secondary Performance Indexes & Constraints\n`;
      dump += `-- --------------------------------------------------------\n`;
      for (const [name, sql] of indices) {
        if (sql) dump += `${sql};\n`;
      }
      dump += '\n';
    }

    dump += `COMMIT;\n`;
    return dump;
  }

  async testConnection(): Promise<ConnectionTestResult> {
    const start = performance.now();
    try {
      if (!this.db) {
        await this.connect();
      }
      if (!this.db) {
        return { success: false, message: 'Database could not be initialized.' };
      }
      const res = this.db.exec('SELECT sqlite_version() as version;');
      const version = (res[0]?.values[0]?.[0] as string) || '3.x';
      const latency = Math.round(performance.now() - start);

      const tableRes = this.db.exec("SELECT count(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'");
      const tableCount = Number(tableRes[0]?.values[0]?.[0] || 0);

      return {
        success: true,
        message: `Successfully connected to SQLite (${tableCount} tables loaded)`,
        latencyMs: latency,
        serverVersion: `SQLite v${version}`
      };
    } catch (err: any) {
      return {
        success: false,
        message: err?.message || 'Failed to connect to database',
        latencyMs: Math.round(performance.now() - start)
      };
    }
  }

  async extractSchema(): Promise<DatabaseSchema> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    // 1. Get all user tables
    const tablesQuery = `
      SELECT name, sql 
      FROM sqlite_master 
      WHERE type='table' AND name NOT LIKE 'sqlite_%'
      ORDER BY name ASC;
    `;
    const tablesRes = this.db.exec(tablesQuery);
    const rawTables = tablesRes[0]?.values || [];

    const tables: TableSchema[] = [];
    let totalCols = 0;
    let totalIdx = 0;
    let totalFks = 0;
    let totalRows = 0;

    for (const [tName] of rawTables) {
      const tableName = String(tName);

      // PRAGMA table_info
      // cid, name, type, notnull, dflt_value, pk
      const colInfoRes = this.db.exec(`PRAGMA table_info("${tableName}");`);
      const colValues = colInfoRes[0]?.values || [];

      // PRAGMA foreign_key_list
      // id, seq, table, from, to, on_update, on_delete, match
      const fkRes = this.db.exec(`PRAGMA foreign_key_list("${tableName}");`);
      const fkValues = fkRes[0]?.values || [];

      // PRAGMA index_list
      // seq, name, unique, origin, partial
      const idxRes = this.db.exec(`PRAGMA index_list("${tableName}");`);
      const idxValues = idxRes[0]?.values || [];

      // Row count
      let rowCount = 0;
      try {
        const countRes = this.db.exec(`SELECT COUNT(*) FROM "${tableName}";`);
        rowCount = Number(countRes[0]?.values[0]?.[0] || 0);
      } catch {
        rowCount = 0;
      }
      totalRows += rowCount;

      // Sample rows (first 10 for quick preview)
      let sampleRows: Record<string, any>[] = [];
      try {
        const sampleRes = this.db.exec(`SELECT * FROM "${tableName}" LIMIT 10;`);
        if (sampleRes[0]) {
          const cols = sampleRes[0].columns;
          sampleRows = sampleRes[0].values.map(vals => {
            const row: Record<string, any> = {};
            cols.forEach((col, i) => {
              row[col] = vals[i];
            });
            return row;
          });
        }
      } catch {
        sampleRows = [];
      }

      // Format foreign keys
      const foreignKeys: ForeignKeySchema[] = fkValues.map(fk => ({
        columnName: String(fk[3]),
        referencedTable: String(fk[2]),
        referencedColumn: String(fk[4] || 'id'),
        onUpdate: String(fk[5] || 'NO ACTION'),
        onDelete: String(fk[6] || 'NO ACTION'),
        inferred: false,
        confidence: 100
      }));
      totalFks += foreignKeys.length;

      // Format indexes
      const indexes: IndexSchema[] = [];
      for (const idx of idxValues) {
        const idxName = String(idx[1]);
        const isUnique = Number(idx[2]) === 1;
        const isPrimary = String(idx[3]) === 'pk';

        // Get index columns
        const idxColsRes = this.db.exec(`PRAGMA index_info("${idxName}");`);
        const idxCols = (idxColsRes[0]?.values || []).map(v => String(v[2]));

        indexes.push({
          name: idxName,
          columns: idxCols,
          isUnique,
          isPrimary
        });
      }
      totalIdx += indexes.length;

      // Format columns & primary key
      const primaryKeys: string[] = [];
      const columns: ColumnSchema[] = colValues.map(c => {
        const colName = String(c[1]);
        const dataType = String(c[2] || 'TEXT').toUpperCase();
        const isNotNull = Number(c[3]) === 1;
        const defaultValue = c[4];
        const isPk = Number(c[5]) > 0;
        const isFk = foreignKeys.some(f => f.columnName === colName);

        if (isPk) {
          primaryKeys.push(colName);
        }

        return {
          name: colName,
          dataType,
          isNullable: !isNotNull,
          isPrimaryKey: isPk,
          isForeignKey: isFk,
          defaultValue: defaultValue !== null ? String(defaultValue) : undefined
        };
      });
      totalCols += columns.length;

      tables.push({
        name: tableName,
        type: 'table',
        rowCount,
        columns,
        indexes,
        primaryKey: primaryKeys,
        foreignKeys,
        sampleRows
      });
    }

    return {
      tables,
      databaseName: this.databaseName,
      databaseType: 'sqlite',
      extractedAt: new Date().toISOString(),
      summary: {
        totalTables: tables.length,
        totalColumns: totalCols,
        totalIndexes: totalIdx,
        totalForeignKeys: totalFks,
        totalEstimatedRows: totalRows
      }
    };
  }

  async profileTable(tableName: string, maxRows = 500): Promise<{
    nullCounts: Record<string, number>;
    distinctCounts: Record<string, number>;
    sampleRows: Record<string, any>[];
    totalRows: number;
  }> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    const totalCountRes = this.db.exec(`SELECT COUNT(*) FROM "${tableName}";`);
    const totalRows = Number(totalCountRes[0]?.values[0]?.[0] || 0);

    const sampleRes = this.db.exec(`SELECT * FROM "${tableName}" LIMIT ${Math.min(maxRows, 1000)};`);
    if (!sampleRes[0]) {
      return { nullCounts: {}, distinctCounts: {}, sampleRows: [], totalRows };
    }

    const columns = sampleRes[0].columns;
    const values = sampleRes[0].values;
    const nullCounts: Record<string, number> = {};
    const distinctSets: Record<string, Set<any>> = {};

    columns.forEach(col => {
      nullCounts[col] = 0;
      distinctSets[col] = new Set();
    });

    const sampleRows: Record<string, any>[] = [];

    for (const rowVals of values) {
      const rowObj: Record<string, any> = {};
      columns.forEach((col, i) => {
        const val = rowVals[i];
        rowObj[col] = val;
        if (val === null || val === undefined || val === '') {
          nullCounts[col]++;
        } else {
          distinctSets[col].add(val);
        }
      });
      sampleRows.push(rowObj);
    }

    const distinctCounts: Record<string, number> = {};
    columns.forEach(col => {
      distinctCounts[col] = distinctSets[col].size;
    });

    return {
      nullCounts,
      distinctCounts,
      sampleRows: sampleRows.slice(0, 50),
      totalRows
    };
  }

  async executeQuery(query: string, options?: { maxRows?: number }): Promise<QueryResult> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    const limit = options?.maxRows || 200;
    const startTime = performance.now();

    // Check if query starts with destructive commands
    const trimmed = query.trim().toUpperCase();
    if (
      trimmed.startsWith('DROP ') ||
      trimmed.startsWith('DELETE ') ||
      trimmed.startsWith('TRUNCATE ') ||
      trimmed.startsWith('ALTER ') ||
      trimmed.startsWith('UPDATE ') ||
      trimmed.startsWith('INSERT ')
    ) {
      throw new Error('Direct execution of data modification queries is blocked in Read-Only mode. Please use the Safe Recommendation & Approval Center.');
    }

    const res = this.db.exec(query);
    const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;

    if (!res[0]) {
      return {
        columns: [],
        rows: [],
        rowCount: 0,
        executionTimeMs
      };
    }

    const columns = res[0].columns;
    const allRows = res[0].values.map(rowVals => {
      const row: Record<string, any> = {};
      columns.forEach((col, i) => {
        row[col] = rowVals[i];
      });
      return row;
    });

    const limitedRows = allRows.slice(0, limit);

    // Recommend chart type based on columns and row count
    let chartRecommendation: 'bar' | 'line' | 'pie' | 'area' | 'table' = 'table';
    let xAxisKey: string | undefined;
    let yAxisKey: string | undefined;

    if (columns.length === 2 && limitedRows.length > 0) {
      const col1 = columns[0];
      const col2 = columns[1];
      const val2 = limitedRows[0][col2];

      if (typeof val2 === 'number') {
        xAxisKey = col1;
        yAxisKey = col2;
        chartRecommendation = limitedRows.length <= 6 ? 'pie' : 'bar';
      }
    } else if (columns.length >= 2) {
      const numCol = columns.find(c => typeof limitedRows[0]?.[c] === 'number');
      const textCol = columns.find(c => typeof limitedRows[0]?.[c] === 'string');
      if (numCol && textCol) {
        xAxisKey = textCol;
        yAxisKey = numCol;
        chartRecommendation = 'bar';
      }
    }

    return {
      columns,
      rows: limitedRows,
      rowCount: allRows.length,
      executionTimeMs,
      chartRecommendation,
      xAxisKey,
      yAxisKey
    };
  }

  async executeModification(sqlOrOp: string): Promise<{ success: boolean; affectedRows?: number; message?: string }> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    try {
      this.db.exec(sqlOrOp);
      const changesRes = this.db.exec('SELECT changes() as changed;');
      const affectedRows = Number(changesRes[0]?.values[0]?.[0] || 0);

      // Persist changes to disk if filePath is configured
      if (this.filePath) {
        try {
          const binary = this.db.export();
          fs.writeFileSync(this.filePath, Buffer.from(binary));
        } catch (writeErr) {
          console.warn('Failed to write SQLite updates to disk:', writeErr);
        }
      }

      return {
        success: true,
        affectedRows,
        message: 'Modification applied successfully.'
      };
    } catch (err: any) {
      return {
        success: false,
        message: err?.message || 'Error executing modification'
      };
    }
  }

  async getExplainPlan(query: string): Promise<any> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    try {
      const explainRes = this.db.exec(`EXPLAIN QUERY PLAN ${query}`);
      if (!explainRes[0]) return [];
      const cols = explainRes[0].columns;
      return explainRes[0].values.map(v => {
        const obj: Record<string, any> = {};
        cols.forEach((c, i) => {
          obj[c] = v[i];
        });
        return obj;
      });
    } catch (err: any) {
      return [{ error: err.message }];
    }
  }

  async benchmarkQuery(query: string, iterations = 3): Promise<{ averageExecutionMs: number; minMs: number; maxMs: number }> {
    if (!this.db) await this.connect();
    if (!this.db) throw new Error('Database not connected');

    const times: number[] = [];
    for (let i = 0; i < iterations; i++) {
      const start = performance.now();
      this.db.exec(query);
      const elapsed = performance.now() - start;
      times.push(elapsed);
    }

    const minMs = Math.round(Math.min(...times) * 100) / 100;
    const maxMs = Math.round(Math.max(...times) * 100) / 100;
    const sum = times.reduce((a, b) => a + b, 0);
    const averageExecutionMs = Math.round((sum / times.length) * 100) / 100;

    return { averageExecutionMs, minMs, maxMs };
  }

  exportDatabaseBinary(): Buffer {
    if (!this.db) throw new Error('Database not connected');
    const data = this.db.export();
    return Buffer.from(data);
  }
}
